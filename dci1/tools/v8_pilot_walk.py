#!/usr/bin/env python3
"""Walk the v8 pilot lifecycle with no model and write
`reports/dci1v8dev/pilot_walk.md`: the producer/consumer matrix against the
payloads the walk really produced, the four criteria's synthetic verdicts,
and the generation counts.

    python3 tools/v8_pilot_walk.py            # write the report
    python3 tools/v8_pilot_walk.py --check    # fail if the matrix would change

Nothing here touches a real root: the walk runs in a temporary directory in
the `dci1v8-synthetic` namespace, and `StudyContext` refuses a root that
overlaps any real tree.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
sys.path.insert(0, str(HERE.parent))

REPORT = HERE.parent / "reports" / "dci1v8dev" / "pilot_walk.md"
MACHINE = HERE.parent / "reports" / "dci1v8dev" / "pilot_walk.json"


def build() -> tuple[str, dict]:
    from dci1v8dev.run import contracts
    from dci1v8dev.run import stages as S
    from tests_v8dev import pilot_harness as H

    with tempfile.TemporaryDirectory(prefix="v8-pilot-walk-") as tmp:
        walked = H.walk(pathlib.Path(tmp))
        payloads = walked["payloads"]
        audit = contracts.audit_contracts(payloads)
        matrix = contracts.matrix_markdown(payloads)
        report = payloads[S.STAGE_REPORT]
    criteria = {k: v["passed"] for k, v in report["criteria"].items()}
    machine = {"contract": audit, "criteria": report["criteria"],
               "generations": report["generations"],
               "stages": list(payloads)}
    lines = [
        "# DCI-1 v8 pilot — synthetic walk (producer / consumer, criteria)",
        "",
        "> Generated by `dci1/tools/v8_pilot_walk.py`. Do not edit by hand.",
        "> The walk runs the nine pilot stages through the production runners",
        "> in the `dci1v8-synthetic` namespace with a scripted generator; the",
        "> rows are fixtures and the verdicts are about the plumbing, not a",
        "> model.",
        "",
        f"Stages walked: {len(payloads)} / {len(S.STAGE_SEQUENCE)} "
        f"({', '.join(payloads)}).",
        "",
        f"Contract: {audit['n_fields']} fields, "
        f"{len(audit['defects'])} defects, "
        f"{audit['n_checked_against_payloads']} checked against payloads.",
        "",
        "## Criteria on the synthetic walk",
        "",
        "| criterion | passed |",
        "|---|---|",
    ]
    for name, ok in criteria.items():
        lines.append(f"| {name} | {ok} |")
    lines += ["", "## Generations", "", "| stage | rows |", "|---|---:|"]
    for k, v in report["generations"].items():
        lines.append(f"| {k} | {v} |")
    lines += ["", "## Producer / consumer matrix", "", matrix]
    return "\n".join(lines) + "\n", machine


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, machine = build()
    if args.check:
        current = REPORT.read_text() if REPORT.exists() else ""
        if current.split("## Criteria")[0] != text.split("## Criteria")[0]:
            print("pilot_walk.md is stale", file=sys.stderr)
            return 1
        print("pilot_walk.md is current")
        return 0
    REPORT.write_text(text)
    MACHINE.write_text(json.dumps(machine, indent=1, sort_keys=True,
                                  default=str) + "\n")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
