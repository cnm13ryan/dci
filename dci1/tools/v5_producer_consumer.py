#!/usr/bin/env python3
"""Emit `reports/dci1v5/v5_producer_consumer.md` from the contract and a walk.

The static contract says which stage produces each field and which stages read
it. Whether the producer *actually writes* it is a fact about a payload, so
this runs the synthetic lifecycle --- eighteen stages, no model, its own
namespace, a temporary evidence root --- and reports each field against the
payload its declared producer really emitted.

    python3 tools/v5_producer_consumer.py            # write the report
    python3 tools/v5_producer_consumer.py --check    # fail if it would change

Nothing here touches the registered v5 roots: the walk runs under a temporary
directory in the `synthetic` namespace, and `StudyContext` refuses a synthetic
root that overlaps the registered one.
"""
from __future__ import annotations

import argparse
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
sys.path.insert(0, str(HERE.parent))

REPORT = HERE.parent / "reports" / "dci1v5" / "v5_producer_consumer.md"

HEADER = """# DCI-1 v5 — producer / consumer contract

Every structured field one v5 stage reads from another, with the stage that
produces it, the stages that read it, whether it is required, the test that
covers it, and whether the eighteen-stage synthetic lifecycle actually
exercised it.

> Generated by `dci1/tools/v5_producer_consumer.py`. Do not edit by hand.
> The `exercised` column comes from a real walk, not from the declaration:
> a field whose declared producer does not write it reads `MISSING` here even
> though the static contract is satisfied.

**The rule this table enforces: no consumer field without a producer.** A
required field that no stage writes on the legal production path is a blocking
defect, not a documentation gap --- the reader would be reading a value that
the pipeline never put there.

"""


def build() -> str:
    from tests_v5 import synthetic_lifecycle as SL

    SL.resolved_manifest()
    try:
        with tempfile.TemporaryDirectory() as tmp:
            walked = SL.walk(pathlib.Path(tmp))
            from dci1v5.protocol import constants as C
            from dci1v5.run import contracts

            payloads = walked["payloads"]
            audit = contracts.audit_contracts(payloads)
            rows = contracts.matrix_rows(payloads)
            table = contracts.matrix_markdown(payloads)
    finally:
        SL.restore()

    artifacts = sorted({r["artifact"] for r in rows})
    exercised = sum(1 for r in rows if r["exercised"])
    required = sum(1 for r in rows if r["required"])
    lines = [HEADER, "## Summary\n"]
    lines.append(f"- **{len(rows)} fields** across **{len(artifacts)} "
                 f"artifacts**, of which {required} are required.")
    lines.append(f"- **{exercised} exercised** by the synthetic lifecycle; "
                 f"{len(rows) - exercised} not reached.")
    lines.append(f"- Defects: **{len(audit['defects'])}** "
                 f"({'clean' if audit['clean'] else 'NOT CLEAN'}).")
    lines.append(f"- Stages walked: {len(payloads)} of "
                 f"{len(C.STAGE_SEQUENCE)}.\n")
    if audit["defects"]:
        lines.append("### Defects\n")
        for defect in audit["defects"]:
            lines.append(f"- `{defect}`")
        lines.append("")
    lines.append("## Per-artifact counts\n")
    lines.append("| artifact | fields | required | exercised |")
    lines.append("|---|---:|---:|---:|")
    for artifact in artifacts:
        subset = [r for r in rows if r["artifact"] == artifact]
        lines.append(
            f"| `{artifact}` | {len(subset)} | "
            f"{sum(1 for r in subset if r['required'])} | "
            f"{sum(1 for r in subset if r['exercised'])} |")
    lines.append("\n## The matrix\n")
    lines.append(table)
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the report on disk is not current")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = REPORT.read_text() if REPORT.exists() else ""
        if current != text:
            print(f"{REPORT} is out of date; re-run without --check")
            return 1
        print(f"{REPORT} is current")
        return 0
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(text)
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
