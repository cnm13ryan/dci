#!/usr/bin/env python3
"""Append the simulation, backtest and scenario results to the design note
(section 9), regenerating that section from the JSON reports.

    python3 tools/v8_append_results.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

DCI1 = Path(__file__).resolve().parents[1]
REP = DCI1 / "reports" / "dci1v8dev" / "prescreen"
DOC = DCI1 / "docs" / "v8_prescreen_spectrum_redesign.md"
MARK = "## 9. Simulation and backtest results"


def _f(x, nd=2):
    return "—" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def _load(path):
    with open(path) as f:
        return json.load(f)


def main() -> int:
    sim = _load(REP / "simulation.json")
    bt = _load(REP / "backtest.json")
    sc = _load(REP / "spectrum_scenarios.json")
    L = [MARK, "",
         "All numbers below are generated by the tools named in "
         "`reports/dci1v8dev/prescreen/README.md`; the JSON files are the record.",
         "", "### 9.1 Synthetic operating characteristics (`simulation.md`)", "",
         f"{sim['n_sims']} replicates per archetype and A-curve; FP/FN against the "
         "true event on the true parameters; the legacy screen is the v7 per-family "
         "C4 certificate on the 24-topic point estimates.", "",
         f"Prospective choice ({sim['chosen']['rule']}):", ""]
    ch = sim["chosen"]["chosen"]
    L.append(f"**event = {ch['event']}, offsets below/above = {ch['d_below']}/{ch['d_above']}, "
             f"accept = {ch['accept']}, reject = {ch['reject']}, final-at-max = "
             f"{ch['final_accept_at']}** → pooled FP {ch['fp']:.3f}, FN {ch['fn']:.3f}, "
             f"resampled {ch['fraction_resampled']:.2f}.")
    L += ["", "| archetype | A curve | true event | legacy pass | legacy FP | legacy FN | "
          "new accept | new FP | new FN | resampled | batches | P(cal C4 \\| legacy pass) | "
          "P(cal event \\| new accept) |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sim["results"]:
        g = r["grid"]
        if (g["event"], g["d_below"], g["d_above"], r["accept"], r["reject"],
                r["final_accept_at"]) != (ch["event"], ch["d_below"], ch["d_above"],
                                          ch["accept"], ch["reject"], ch["final_accept_at"]):
            continue
        for k, v in r["per_archetype"].items():
            Lg, N = v["legacy"], v["new"]
            L.append(f"| {k} | {r['a_curve']} | {v['true_event']} | {_f(Lg['pass_rate'])} | "
                     f"{_f(Lg['false_positive_rate'])} | {_f(Lg['false_negative_rate'])} | "
                     f"{_f(N['accept_rate'])} | {_f(N['false_positive_rate'])} | "
                     f"{_f(N['false_negative_rate'])} | {_f(N['fraction_resampled'])} | "
                     f"{_f(N['mean_batches'])} | {_f(Lg['calibrated_c4_given_pass'])} | "
                     f"{_f(N['calibrated_event_given_accept'])} |")
    L += ["", "### 9.2 Backtest on the twelve stored replications (`backtest.md`, `failure_table.md`)", "",
          f"Screen configuration: {bt['config']}. The second pass is emulated from "
          "Calibration-A's per-topic rows (no reserve, no A-grid re-measurement); "
          "'Calibration-B only' shares no topic with the carved batches.", ""]
    for truth, block in bt["summary"].items():
        L += [f"**Truth: {truth}**", "",
              "| screen | predicted + | true + | TP | FP | FN | precision | recall | FPR |",
              "|---|---|---|---|---|---|---|---|---|"]
        for name, m in block.items():
            L.append(f"| {name} | {m['n_predicted_positive']} | {m['n_true_positive']} | {m['tp']} | "
                     f"{m['fp']} | {m['fn']} | {_f(m['precision'])} | {_f(m['recall'])} | "
                     f"{_f(m['false_positive_rate'])} |")
        L.append("")
    L += [f"Pre-screen PASS → calibration FAIL: {bt['n_pass_to_fail_families']} of "
          f"{bt['n_prescreen_pass_families']} family-level passes. Causes: "
          + ", ".join(f"{c} {n}" for c, n in bt["failure_causes"].items() if n) + ".", "",
          "| tree | model | legacy groups pre → cal | pass→fail | stage-1 accept/resample | "
          "final accept (calibrated true) | forwarded new / legacy | re-screen gens | "
          "calibration gens new / legacy |", "|---|---|---|---|---|---|---|---|---|"]
    for r in bt["replication_level"]:
        L.append(f"| {r['tree']} | {r['model']} | {r['legacy_groups_prescreen']} → "
                 f"{r['groups_calibrated']} | {r['n_pass_to_fail']} | {r['stage1_accept']}/"
                 f"{r['stage1_resample']} | {r['final_accept']} ({r['final_accept_calibrated_true']}) | "
                 f"{r['forwarded_new']} / {r['forwarded_legacy']} | {r['rescreen_cost']} | "
                 f"{r['calibration_cost_new']} / {r['calibration_cost_legacy']} |")
    lr = bt["local_recovery"]
    L += ["", f"Local-reference recovery: {len(lr)} families calibrated inside the ±0.10 caliper; "
          f"kept by the new retention {sum(1 for x in lr if x['forwarded_new'])}, by §12.7 "
          f"{sum(1 for x in lr if x['forwarded_legacy'])}.", ""]
    for key in ("lomo_support_both", "lomo_c4"):
        lo = bt[key]
        L += [f"**{lo['label']}** ({lo['p_key']} vs {lo['truth_key']}, min recall {lo['min_recall']}):", "",
              "| held-out model | chosen accept | test precision | test recall | test FPR | test n+ |",
              "|---|---|---|---|---|---|"]
        for m, v in lo["per_held_out_model"].items():
            te = v["test"]
            L.append(f"| {m} | {v['chosen_accept']} | {_f(te['precision'])} | {_f(te['recall'])} | "
                     f"{_f(te['false_positive_rate'])} | {te['n_true_positive']} |")
        L.append("")
    L += ["### 9.3 Constructed-pool scenarios (`spectrum_scenarios.md`)", "",
          "| scenario | expectation | old C4 | families meeting old C4 | new status | beyond V_head | rejections |",
          "|---|---|---|---|---|---|---|"]
    for name, s in sc.items():
        inner = s.get("after", s)
        L.append(f"| {name} | {s['expect']} | {inner.get('old_c4')} | "
                 f"{', '.join(inner.get('families_meeting_old_c4', [])) or '—'} | "
                 f"{inner.get('new_status')} | {inner.get('beyond_v_head')} | "
                 f"{json.dumps(inner.get('spectrum_rejections', {}))} |")
    text = DOC.read_text()
    head = text.split(MARK)[0]
    DOC.write_text(head + "\n".join(L) + "\n")
    print("appended", DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main())
