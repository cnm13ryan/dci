"""Generations carried from v4r3, and the identity checks that let them be.

**What is carried and what is not.** A generation row is a model's answer to a
rendered prompt under a fixed decoding configuration. That is the expensive
part of this study and it does not become wrong when the protocol revision
changes: the model is the same model at the same revision, the decoding is the
same decoding, and --- this is the part that has to be *checked* rather than
assumed --- the prompt is the same prompt, byte for byte.

What is **not** carried is any derived quantity. Verdicts, compliance rates,
vacuity, the difficulty table: all recomputed by v4r4's verifier, under v4r4's
canonical hash, from the carried text. §10.6 forbids carrying a stale hash
forward on the grounds that behaviour looks unchanged, and a verdict is a
number produced by a hash. `stages/reuse.py` classifies this as
`RECOMPUTED_FROM_EXISTING_RAW_DATA` and says so on the record.

**The check that does the work.** `carried_rows` refuses unless, for every row
the v4r4 cell plan wants, the source run holds a row with the same `row_id`
whose stored `user_prompt` is byte-identical to the one v4r4 renders now and
whose `prompt_hash` agrees. A wording that changed anywhere fails here, by row,
with the row named --- which is what makes "a changed prompt invalidates its
evidence" a property of the code rather than a policy in a document.

**What is deliberately not required to match: the scientific seed.** v4r4's
seed domain is `dci1v4r4:gen:v1` and v4r3's was `dci1v4r3:gen:v1`, so the seed
a v4r4 plan derives for a row differs from the one the row was drawn under.
That is not a defect and pretending otherwise would be worse: the seed selects
*which* draw from the model's distribution was taken, and a draw taken under
another seed is still a draw from the same distribution at the same prompt and
temperature. Both seeds are recorded on the provenance block, so a reader can
see that the row was not generated by this study's own seed schedule.

The consequence is honest and small: v4r4's carried rows are **not
reproducible from v4r4's seed schedule alone**. They are reproducible from
v4r3's, which is preserved. A stage that regenerated instead would get
different draws and would be a different measurement -- which is exactly why
the choice between carrying and regenerating is made in the ledger and not
here.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

from dci1v4.engine import fs
from dci1v4.errors import ProtocolError
from dci1v4.protocol.hashing import canonical_json, sha_file, sha_text

__all__ = ["CarriedRun", "CARRIED_FILES", "load_carried_run",
           "stage_carried_source", "carried_rows", "write_carry_note"]

#: The files a carried run brings across. `design.jsonl` and `rows.jsonl` are
#: the evidence; `backend.log` and `plan.json` are the execution condition and
#: come with them, because a row whose backend log lives in another study's
#: tree is a row whose provenance is a path away from being lost.
CARRIED_FILES = ("design.jsonl", "rows.jsonl", "plan.json", "backend.log",
                 "rows_engine.json")


@dataclass(frozen=True)
class CarriedRun:
    """One source backend run, indexed by row identity."""

    study: str
    run_dir: Path
    design: Mapping[str, Mapping[str, Any]]
    produced: Mapping[str, Mapping[str, Any]]

    @property
    def source(self) -> dict[str, Any]:
        return {
            "study": self.study,
            "run_dir": str(self.run_dir),
            "design_hash": sha_file(self.run_dir / "design.jsonl"),
            "rows_hash": sha_file(self.run_dir / "rows.jsonl"),
            "rows_available": len(self.produced),
        }


def _read(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        raise ProtocolError(f"carried run is missing {path}")
    return [json.loads(line) for line in path.read_text().splitlines()
            if line.strip()]


def load_carried_run(run_dir: Path, *, study: str) -> CarriedRun:
    run_dir = Path(run_dir)
    design = {row["row_id"]: row for row in _read(run_dir / "design.jsonl")}
    produced = {row["row_id"]: row for row in _read(run_dir / "rows.jsonl")}
    orphans = sorted(set(produced) - set(design))
    if orphans:
        raise ProtocolError(
            f"{run_dir}: {len(orphans)} generated rows have no design row "
            f"({orphans[:3]}); the source run is not internally consistent "
            "and nothing may be carried from it")
    return CarriedRun(study=study, run_dir=run_dir, design=design,
                      produced=produced)


def carried_rows(carried: CarriedRun, wanted: Sequence[Mapping[str, Any]]
                 ) -> dict[str, Any]:
    """The source rows, in the order this plan wants them, or a refusal.

    Every failure mode is named separately, because they mean different
    things: a missing row means the source did not measure this instrument, a
    changed prompt means the treatment moved, and a changed prompt hash with
    an unchanged prompt would mean the hashing itself moved.
    """
    missing: list[str] = []
    prompt_changed: list[dict[str, str]] = []
    hash_changed: list[str] = []
    rows: list[Mapping[str, Any]] = []
    seeds_differ = 0
    for row in wanted:
        row_id = row["row_id"]
        source = carried.design.get(row_id)
        produced = carried.produced.get(row_id)
        if source is None or produced is None:
            missing.append(row_id)
            continue
        if source.get("user_prompt") != row["user_prompt"]:
            prompt_changed.append({
                "row_id": row_id,
                "carried": str(source.get("user_prompt"))[-90:],
                "rendered_now": str(row["user_prompt"])[-90:]})
            continue
        if source.get("prompt_hash") != row["prompt_hash"]:
            hash_changed.append(row_id)
            continue
        if source.get("scientific_seed") != row["scientific_seed"]:
            seeds_differ += 1
        rows.append(produced)

    if missing or prompt_changed or hash_changed:
        raise ProtocolError(
            f"§10.7 E: {len(wanted)} rows were wanted from {carried.run_dir}; "
            f"{len(missing)} are absent ({missing[:3]}), "
            f"{len(prompt_changed)} were generated under a different "
            f"model-facing prompt ({prompt_changed[:1]}), and "
            f"{len(hash_changed)} carry a prompt hash that no longer "
            f"recomputes ({hash_changed[:3]}). Evidence does not survive a "
            "change in what determines it")

    return {
        "rows": rows,
        "provenance": {
            "carried": True,
            "source": carried.source,
            "rows_carried": len(rows),
            "rows_wanted": len(wanted),
            "rows_in_source_not_wanted":
                len(carried.produced) - len(rows),
            "seeds_differ": seeds_differ,
            "seed_note":
                "the scientific seed differs on every row because the seed "
                "domain carries the study id. The prompt, the model, the "
                "revision and the decoding are identical, which is what "
                "determines the distribution the draw came from",
            "verdicts": "recomputed under this study's verifier, not carried",
        },
    }


def write_carry_note(run_dir: Path, note: Mapping[str, Any]) -> Path:
    """The provenance file that sits beside every carried run's rows."""
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)
    payload = {"artifact_type": "v4r4-carried-generation-note", **dict(note)}
    payload["note_hash"] = sha_text(canonical_json(payload))
    path = run_dir / "carried_from.json"
    fs.write_json(path, payload)
    return path


def stage_carried_source(source_run_dir: Path, dest_run_dir: Path, *,
                         study: str, reason: str) -> CarriedRun:
    """Copy a source run into this study's tree, once, and index it there.

    The copy is what keeps the rest of this package honest about isolation.
    Everything downstream reads `dest_run_dir`, which is a v4r4 path holding
    v4r4's own copy of the rows and a `carried_from.json` saying where they
    came from and why. Nothing later has to reach into the superseded study's
    tree, and nothing later could mistake the rows for locally generated ones:
    the note is beside them and the scored rows carry `carried_from`.
    """
    source_run_dir, dest_run_dir = Path(source_run_dir), Path(dest_run_dir)
    dest_run_dir.mkdir(parents=True, exist_ok=True)
    copied: dict[str, str] = {}
    for name in CARRIED_FILES:
        source = source_run_dir / name
        if not source.exists():
            continue
        (dest_run_dir / name).write_bytes(source.read_bytes())
        copied[name] = sha_file(source)
    if "rows.jsonl" not in copied:
        raise ProtocolError(
            f"{source_run_dir} holds no rows.jsonl; there is nothing to carry")
    run = load_carried_run(dest_run_dir, study=study)
    write_carry_note(dest_run_dir, {
        "source_study": study,
        "source_run_dir": str(source_run_dir),
        "copied": copied,
        "rows": len(run.produced),
        "reason": reason,
        "classification": "RECOMPUTED_FROM_EXISTING_RAW_DATA",
        "what_is_carried": "the model's answers and the execution condition "
                           "that produced them",
        "what_is_not_carried": "every derived quantity. Verdicts, compliance "
                               "rates, vacuity and the difficulty table are "
                               "recomputed by this study's verifier from the "
                               "carried text",
    })
    return run
