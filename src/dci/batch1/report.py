def _fmt(p: float | None) -> str:
    return "—" if p is None else f"{p:.2f}"


def _params(spec: Mapping[str, Any]) -> str:
    return ", ".join(f"{k}={'+'.join(v) if isinstance(v, list) else v}"
                     for k, v in spec["params"].items())


def library_review(manifest: Mapping[str, Any],
                   matrix: Mapping[str, Any]) -> str:
    out = ["# Batch 1 instruction library: review table", "",
           "Generated by `python -m dci.batch1 write-review-artifacts` from "
           "`library_manifest.json` and `compatibility_matrix.json`. Rows "
           "marked *proposed* are this implementation's proposal (decision "
           "D01) and are not approved.", "",
           f"Verifier bundle hash: `{manifest['verifier_bundle_hash']}`", "",
           "| id | role | operation | object | parameters | F0 (imperative) "
           "| F1 (requirement) | vacuity | compatible B limits | status |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for spec in manifest["focal_a"] + manifest["focal_b"] + manifest["references"]:
        row = matrix["cells"].get(spec["cid"])
        limits = ("all (B itself)" if row is None else
                  " ".join(m for m, cell in row.items()
                           if cell["status"] == "COMPATIBLE") or "none")
        status = "prescribed" if spec["status"] == L.STATUS_PRESCRIBED \
            else "*proposed*"
        out.append(f"| `{spec['cid']}` | {spec['role']} | {spec['operation']} "
                   f"| {spec['object_type']} | {_params(spec)} "
                   f"| {spec['wording']['F0']} | {spec['wording']['F1']} "
                   f"| {spec['non_vacuity']['rule']} | {limits} | {status} |")
    out += ["", "## Family semantics", ""]
    for fam_id, fam in manifest["families"].items():
        out.append(f"- `{fam_id}` ({fam['operation']} / {fam['object_type']},"
                   f" verifier `{fam['verifier_id']}`, {fam['vacuity']}): "
                   f"{fam['semantic']}")
    return "\n".join(out) + "\n"


def compatibility_review(matrix: Mapping[str, Any]) -> str:
    limits = [str(m) for m in matrix["limits"]]
    symbol = {"COMPATIBLE": "✓", "INCOMPATIBLE": "✗", "UNRESOLVED": "?"}
    out = ["# B-specific compatibility matrix", "",
           "✓ compatible (a stored witness passes both verifiers, compliant "
           "under both); ✗ incompatible (proof below); ? unresolved. "
           f"Counts: {matrix['counts']}.", "",
           "| constraint | " + " | ".join(f"B{m}" for m in limits) + " |",
           "|---|" + "---|" * len(limits)]
    for cid, row in matrix["cells"].items():
        out.append(f"| `{cid}` | " + " | ".join(symbol[row[m]["status"]]
                                                for m in limits) + " |")
    out += ["", "## Incompatibility proofs and unresolved cells", ""]
    for cid, row in matrix["cells"].items():
        for m in limits:
            if row[m]["status"] != "COMPATIBLE":
                out.append(f"- `{cid}` × B{m}: {row[m]['status']} — "
                           f"{row[m]['reason']}")
    out += ["", "## Library size by B limit", ""]
    refs = {c.cid for c in L.reference_library()}
    for m in limits:
        n = len(set(matrix["compatible_by_limit"][m]) & refs)
        out.append(f"- B{m}: {n} of {len(refs)} references compatible")
    task = matrix["task_level"]
    words = [cell["words"] for row in task["cells"].values()
             for cell in row.values()]
    out += ["", "## Task-level compatibility (the 60-120 word contract)", "",
            f"Contract: {task['contract']}. Counts: {task['counts']}. "
            f"Witness lengths {min(words)}-{max(words)} words. A witness is a "
            "logical certificate built from a fixed sentence pool, not an "
            "example of good writing, and says nothing about how often a "
            "model complies.", ""]
    if task["unresolved"]:
        out += ["Unresolved for review (not incompatible):", ""] + [
            f"- `{cid}` × B{m}" for cid, m in task["unresolved"]]
    else:
        out.append("Every logically compatible cell has a full-length "
                   "witness.")
    return "\n".join(out) + "\n"


def topic_review(overlap: Mapping[str, Any], hygiene: Mapping[str, Any],
                 revisions: list[Mapping[str, Any]],
                 current: Mapping[str, str] | None = None,
                 semantic: Mapping[str, Any] | None = None) -> str:
    """The generated screen report (``topic_screen_report.md``). The
    researcher-facing explanation is ``TOPIC_REVIEW.md``."""
    from dci.batch1 import text as T
    current = current or {}
    screen = overlap["screen"]
    rare = screen.get("rare_stems", {})
    out = ["# Batch 1 topic bank: screen report", "",
           "Generated by `python -m dci.batch1 write-review-artifacts` from "
           "`topic_overlap.json`, `topic_hygiene.json`, the bank's revision "
           "record and `data/topics_semantic_review.json`. The plain-language "
           "review is [`TOPIC_REVIEW.md`](TOPIC_REVIEW.md). The bank, the "
           "replacements and the review decisions are agent proposals "
           "awaiting the researcher (D05).", "",
           f"- Historical questions compared: {overlap['historical_released']}"
           f" from {', '.join(overlap['historical_sources'])}; sequestered "
           f"hashes: {overlap['historical_sequestered_hashes']}.",
           f"- Screen: word-set Jaccard ≥ {screen['wordset_jaccard']}, "
           f"stemmed content-word Jaccard ≥ {screen['content_jaccard']}, or "
           f"≥ {rare.get('min_shared', '—')} shared rare stems (≥ "
           f"{rare.get('min_letters', '—')} letters, in ≤ "
           f"{rare.get('max_document_frequency', '—')} questions). Exact "
           f"matches: {len(overlap['exact_matches'])}; sequestered matches: "
           f"{len(overlap['sequestered_matches'])}; flagged pairs: "
           f"{len(overlap['flagged_historical'])} historical, "
           f"{len(overlap['flagged_internal'])} internal; unreviewed: "
           f"{len(overlap['unreviewed'])}.",
           f"- Semantic review: {overlap.get('semantic_review', {}).get('findings', 0)}"
           " findings; restatements still in the bank: "
           f"{overlap.get('semantic_review', {}).get('restatements_still_in_bank', [])}.",
           f"- Report clean: **{overlap['clean']}**. Hygiene clean: "
           f"**{hygiene['clean']}** (form, instruction-like content, library "
           "target words).", "",
           f"## Questions revised ({len(revisions)} revision records)", "",
           "| topic | revised | reason | previous question | question now |",
           "|---|---|---|---|---|"]
    for r in revisions:
        out.append(f"| `{r['topic_id']}` | {r['revised_on']} | {r['reason']} | "
                   f"{r['previous_question']} | {current.get(r['topic_id'], '')} |")
    r1 = [r for r in revisions if "R1" in r["reason"]
          or "semantic sweep" in r["reason"]]
    if r1:
        def feats(q):
            return (T.word_count(q), T.max_word_letters(q),
                    "b" in q.lower(), "z" in q.lower())
        before = [feats(r["previous_question"]) for r in r1]
        after = [feats(current.get(r["topic_id"], "")) for r in r1]

        def mean(xs):
            return round(sum(xs) / len(xs), 2)
        out += ["", f"## Balance of the {len(r1)} re-audit rewrites", "",
                "Features that can change how hard an instruction is to "
                "follow on a topic: answers reuse topic words, so a long "
                "word matters for B (word length) and the letters b and z "
                "matter for the letter prohibitions.", "",
                "| feature | previous questions | replacements |",
                "|---|---|---|",
                f"| mean words | {mean([b[0] for b in before])} | "
                f"{mean([a[0] for a in after])} |",
                f"| mean longest word (letters) | {mean([b[1] for b in before])}"
                f" | {mean([a[1] for a in after])} |",
                f"| longest word ≥ 9 letters | {sum(b[1] >= 9 for b in before)}"
                f" | {sum(a[1] >= 9 for a in after)} |",
                f"| contains b | {sum(b[2] for b in before)} | "
                f"{sum(a[2] for a in after)} |",
                f"| contains z | {sum(b[3] for b in before)} | "
                f"{sum(a[3] for a in after)} |",
                f"| same opening word | — | "
                f"{sum(r['previous_question'].split()[0] == current.get(r['topic_id'], ' ').split()[0] for r in r1)} of {len(r1)} |"]
    out += ["", "## Flagged pairs kept as distinct", "",
            "| topic | question | neighbour | word / content Jaccard | rare "
            "stems | rationale |", "|---|---|---|---|---|---|"]
    for p in overlap["flagged_historical"] + overlap["flagged_internal"]:
        out.append(f"| `{p['topic_id']}` | {p['question']} | "
                   f"{p['neighbour_source']}:{p['neighbour_id']} — "
                   f"{p['neighbour']} | {p['wordset_jaccard']:.2f} / "
                   f"{p['content_jaccard']:.2f} | "
                   f"{', '.join(p.get('rare_shared', [])) or '—'} | "
                   f"{p['decision'] or 'UNREVIEWED'} |")
    if semantic:
        kept = [f for f in semantic.get("findings", [])
                if f["action"] == "kept" and f["verdict"] == "CLOSE"]
        out += ["", f"## Semantic review: CLOSE questions kept ({len(kept)})",
                "", "Same narrow subject as a historical or bank question, "
                "but a different question.", "",
                "| pass | topic | question | close to | rationale |",
                "|---|---|---|---|---|"]
        for f in kept:
            out.append(f"| {f['pass']} | `{f['topic_id']}` | {f['question']} | "
                       f"{f['matched']} ({f['matched_source']}) | "
                       f"{f['rationale']} |")
        contained = [f for f in semantic.get("findings", [])
                     if f["pass"].startswith("containment")]
        if contained:
            out += ["", f"## Containment pass: the kept CLOSE pairs re-judged "
                    f"({len(contained)})", "",
                    "Rule (D05, 2026-10-25): a pair is a restatement when a "
                    "good answer to either question would largely answer the "
                    "other, in either direction. Two judges, each blind to "
                    "the other; a restatement by either is rewritten.", "",
                    "| topic | question | close to | verdict | judges |",
                    "|---|---|---|---|---|"]
            for f in contained:
                out.append(f"| `{f['topic_id']}` | {f['question']} | "
                           f"{f['matched']} ({f['matched_source']}) | "
                           f"{f['verdict']} ({f['action']}) | "
                           f"{f['rationale']} |")
    out += ["", "## Stage 1, Stage 2 and reserved topic characteristics", "",
            "Refined cells pool Stage 1 and Stage 2 topics; unrefined cells see "
            "Stage 1 only. Differences here can move difficulty "
            "independently of the instruction; Freeze 2 reports a "
            "Stage-1-only sensitivity for that reason.", "",
            "| set | n | mean words | mean longest word | longest ≥ 9 | ≥ 11 | "
            "≥ 13 | has b | has z | why | how |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, prof in hygiene["profiles"].items():
        if not prof.get("n"):              # bank v2 reserves no topics
            out.append(f"| {name} | 0 | — | — | — | — | — | — | — | — | — |")
            continue
        out.append(f"| {name} | {prof['n']} | {prof['mean_words']} | "
                   f"{prof['mean_longest_word']} | {prof['share_longest_ge_9']:.2f}"
                   f" | {prof['share_longest_ge_11']:.2f} | "
                   f"{prof['share_longest_ge_13']:.2f} | "
                   f"{prof['share_with_letter_b']:.2f} | "
                   f"{prof['share_with_letter_z']:.2f} | {prof['share_why']:.2f}"
                   f" | {prof['share_how']:.2f} |")
    return "\n".join(out) + "\n"


#: The generated block inside the hand-written ``TOPIC_REVIEW.md``.
GENERATED_BEGIN = ("<!-- BEGIN GENERATED: topic replacement tables "
                   "(python -m dci.batch1 write-review-artifacts) -->")
GENERATED_END = "<!-- END GENERATED -->"

#: Which revision records each replacement table shows, by reason prefix,
#: and how its reason column reads.
_REPLACEMENT_KINDS = (
    ("re-audit R1", "a", "restatement (named by the re-audit)"),
    ("semantic sweep 2026-10-19: restated", "b",
     "restatement (found by the semantic review)"),
    ("semantic sweep 2026-10-19: same subject", "b",
     "close to a historical question"),
    ("semantic sweep 2026-10-19: duplicated", "b",
     "duplicate of another new question"),
    ("D05 2026-10-25: containment rule", "c",
     "restatement under the containment rule"),
    ("D05 2026-10-25: long word restored", "c",
     "reworded to restore an 11+-letter word in Stage 1"),
)
_USED_IN = {"stage1": "Stage 1 (pilot)", "stage2": "Stage 2 (pilot)",
            "confirmatory": "reserved confirmatory"}


def _partner_at_review(r: Mapping[str, Any],
                       findings: list[Mapping[str, Any]]) -> str | None:
    """A bank partner's text as the reviewer read it: the finding against
    this revision's previous question, not the partner's text today."""
    matched = r.get("matched") or {}
    if matched.get("question"):
        return matched["question"]
    for f in findings:
        if f.get("topic_id") == r["topic_id"] and \
                f.get("matched_source") == matched.get("id") and \
                f.get("question_sha256") == r.get("previous_sha256"):
            return f.get("matched")
    return None


def topic_replacements(revisions: list[Mapping[str, Any]],
                       current: Mapping[str, str],
                       used_in: Mapping[str, str],
                       areas: Mapping[str, str],
                       semantic: Mapping[str, Any] | None = None,
                       history: Mapping[str, str] | None = None) -> str:
    """``TOPIC_REVIEW.md`` §3: every replacement since the re-audit, with
    the original, the replacement and what it overlapped. A replacement
    that was itself replaced later shows the text it had, and says so.
    ``history`` maps a normalised historical question to its source banks:
    a cited question is labelled with them, and one it does not contain is
    marked as not found."""
    findings = list((semantic or {}).get("findings", []))
    shown = []
    for i, r in enumerate(revisions):
        kind = next((k for k in _REPLACEMENT_KINDS
                     if r["reason"].startswith(k[0])), None)
        if kind is None:
            continue
        later = next((x for x in revisions[i + 1:]
                      if x["topic_id"] == r["topic_id"]), None)
        shown.append((kind, r, later))
    order = {"stage1": 0, "stage2": 1, "confirmatory": 2}

    def row(kind, r, later) -> str:
        tid = r["topic_id"]
        text = later["previous_question"] if later else current[tid]
        note = " *(changed again on 2026-10-25, §3c)*" if later else ""
        matched = r.get("matched") or {}
        partner = _partner_at_review(r, findings)
        if not matched:
            cited = "—"
        elif partner is None:
            cited = (f"*(partner text at review not recorded; "
                     f"{matched.get('source')} {matched.get('id', '')})*")
        elif matched.get("source") == "batch1":
            pid = matched.get("id")
            cited = f"new question `{pid}`: {partner} *(new bank)*"
            if partner != current.get(pid):
                cited += (f" — since rewritten as: {current.get(pid)}")
        else:
            source = matched.get("source")
            found = None if history is None else \
                history.get(" ".join(partner.lower().split()))
            if found and source == "historical":
                source = found
            cited = f"{partner} *({source})*"
            if history is not None and not found:
                cited += " *(not found in the historical banks)*"
        return (f"| `{tid}` | {areas[tid]} | {_USED_IN[used_in[tid]]} | "
                f"{r['previous_question']} | **{text}**{note} | {cited} | "
                f"{kind[2]} |")

    head = ["| topic id | category | used in | original question | "
            "replacement | question it overlapped *(source)* | reason |",
            "|---|---|---|---|---|---|---|"]
    out = []
    titles = {"a": "### 3a. The {n} restatements named by the re-audit",
              "b": "### 3b. The other {n} replacements of 2026-10-19",
              "c": "### 3c. The {n} questions rewritten on 2026-10-25 "
                   "(D05 decision)"}
    for section in ("a", "b", "c"):
        rows = sorted((x for x in shown if x[0][1] == section),
                      key=lambda x: (order[used_in[x[1]["topic_id"]]],
                                     x[1]["topic_id"]))
        if not rows:
            continue
        out += ["", titles[section].format(n=len(rows)), ""] + head + \
            [row(*x) for x in rows]
    return "\n".join(out).strip("\n") + "\n"


def splice_generated(document: str, block: str) -> str:
    """Replace the text between the generated-block markers."""
    start = document.index(GENERATED_BEGIN) + len(GENERATED_BEGIN)
    end = document.index(GENERATED_END)
    return document[:start] + "\n\n" + block + "\n" + document[end:]


def estimate_review(est: Mapping[str, Any]) -> str:
    out = ["# Batch 1 pilot: generation-count and cost estimate", "",
           "Generated from `estimate.json`. Historical rates are not a "
           "measurement of any cloud instance.", "",
           f"- Stage 1 generations: **{est['stage1_rows']:,}** "
           f"({', '.join(f'{k} {v:,}' for k, v in est['stage1_by_kind'].items())})",
           f"- Stage 2 ceiling: **{est['stage2_max_rows']:,}** "
           f"({est['stage2_max_cells']} cells × 64)",
           f"- Total ceiling: **{est['total_max_rows']:,}**",
           f"- Storage ceiling: ~{est['storage_bytes_max'] / 1e6:,.0f} MB "
           "(generated rows plus scored records)",
           f"- Generation time at historical rates: Stage 1 "
           f"{est['stage1_hours_at_historical_rates']} h; Stage 2 "
           f"{est['stage2_hours_if_even']} h if spread evenly, at most "
           f"{est['stage2_hours_worst_case']} h", "",
           "| model | Stage 1 rows | Stage 2 rows (even / max) | rows/s "
           "(7900 XTX, v8.1) | Stage 1 h | Stage 2 h (even / max) |",
           "|---|---|---|---|---|---|"]
    for key, v in est["per_model"].items():
        out.append(f"| {key} | {v['stage1_rows']:,} | "
                   f"{v['stage2_rows_if_even']:,} / {v['stage2_rows_max']:,} | "
                   f"{v['historical_rows_per_second']} | "
                   f"{v['stage1_hours_at_historical_rate']} | "
                   f"{v['stage2_hours_if_even']} / {v['stage2_hours_max']} |")
    out += ["", "## Caveats", ""] + [f"- {c}" for c in est["caveats"]]
    return "\n".join(out) + "\n"


