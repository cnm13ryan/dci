def decisions_review(approvals: Mapping[str, Any]) -> str:
    out = ["# Decisions requiring approval before the pilot", "",
           "Every decision must be APPROVED in `approvals.json` against its "
           "payload hash before `execute` will run real generation. "
           "*design* decisions operationalise the research brief; "
           "*proposed* ones are this implementation's choices. Each payload "
           "binds the code that implements the decision (docstrings and "
           "comments excluded), so editing that code voids the approval. "
           "The rationale, revisions and open questions for each decision "
           "are in `README.md` §12 and `REMEDIATION_REPORT.md`.", "",
           "| id | decision | origin | status | payload hash | implementing "
           "code |", "|---|---|---|---|---|---|"]
    impl = {d.decision_id: ", ".join(f"`{m}`" for m in
                                     CFG.IMPLEMENTATION[d.decision_id])
            for d in CFG.decisions()}
    for did, d in approvals["decisions"].items():
        summary = d["summary"].replace("|", "\\|")
        out.append(f"| {did} | **{d['title']}**: {summary} | "
                   f"{d['origin']} | {d['status']} | `{d['payload_hash'][:16]}`"
                   f" | {impl.get(did, '')} |")
    out += ["", "## Changes since the first audit, and what to settle",
            "", "Every payload hash changed in this revision (each now binds "
            "its implementing code), so no earlier approval carries over; "
            "none had been given.", ""]
    for did in approvals["decisions"]:
        change, ask = DECISION_NOTES.get(did, ("", ""))
        out += [f"### {did} — {approvals['decisions'][did]['title']}", "",
                f"- **Change:** {change}", f"- **To settle:** {ask}", ""]
    return "\n".join(out).rstrip() + "\n"


def selection_report(result: Mapping[str, Any], tables: Any,
                     cfg: CFG.PilotConfig) -> str:
    """§25's reference-selection and coverage report. Stand-alone data only;
    there is no interference estimate in it, and none could be computed
    from its inputs."""
    head = "SYNTHETIC DEMONSTRATION — NOT EVIDENCE" if result.get("synthetic") \
        else "Pilot reference selection"
    out = [f"# {head}", "",
           f"Calibration status: **{result['status']}**.", ""]
    b = result["b"]
    out += ["## B selection (D07)", "",
            f"Selected: {b.get('selected')} ({b['status']}).", "",
            "| m | informative model-frames | median compliance |",
            "|---|---|---|"]
    for m, v in b["per_limit"].items():
        out.append(f"| {m} | {v['informative']} | {_fmt(v['median'])} |")
    if b.get("measurement_limitations"):
        out += ["", "Measurement limitations (extreme B compliance, kept, "
                "not removed):", ""] + [f"- {x}" for x in
                                       b["measurement_limitations"]]
    if b.get("evaluated"):
        out += ["", "| pair | admissible | median separation | reasons |",
                "|---|---|---|---|"]
        for e in b["evaluated"]:
            sep = e.get("median_separation")
            out.append(f"| {e['pair']} | {'yes' if e['admissible'] else 'no'} "
                       f"| {_fmt(sep)} | {', '.join(e['reasons']) or '—'} |")
    if result.get("a"):
        a = result["a"]
        out += ["", "## A selection (D08)", "",
                f"Selected: `{a['selected']}` ({a['status']}).", "",
                "| A | admissible | model-frames with headroom | "
                "configurations with G1 support and informative A | "
                "including uninformative A | reasons |",
                "|---|---|---|---|---|---|"]
        for r in a["ranking"]:
            out.append(f"| `{r['a']}` | {'yes' if r['admissible'] else 'no'} | "
                       f"{r['headroom']} | {r['g1_supported']} | "
                       f"{r['g1_supported_including_uninformative_a']} | "
                       f"{', '.join(r['reasons']) or '—'} |")
        out += [""] + [f"- **{f}**" for f in a["flags"]]
    mfs = R.model_frames(cfg)
    out += ["", "## Candidates: eligibility and raw stand-alone compliance",
            "", "Raw compliance per model-frame; κ is task-only spontaneous "
            "compliance per model. An observed rate near a threshold is "
            "marked *borderline*; intervals are in `calibration.json`.", "",
            "| candidate | status | decision | " + " | ".join(
                f"{_SHORT.get(m, m)} {f}" for m, f in mfs)
            + " | κ (models) |",
            "|---|---|---|" + "---|" * len(mfs) + "---|"]
    for cid, e in result["eligibility"].items():
        cells = [_fmt(e["cells"][f"{m}|{f}"].get("p")) for m, f in mfs]
        kap = " ".join(_fmt(tables.kappa(m, cid).p) for m in cfg.models)
        out.append(f"| `{cid}` | {e['status']} | {e['decision']} | "
                   + " | ".join(cells) + f" | {kap} |")
    if result.get("extension_10_only"):
        out += ["", "Admitted at 10% but not at 20% (sensitivity population "
                "only): " + ", ".join(f"`{c}`" for c in
                                      result["extension_10_only"])]
    if result.get("configurations"):
        out += ["", "## Reference populations and coverage per configuration",
                "", "| configuration | p_A | G1 | G2 | G3 | G4 | G5 | G6 | "
                "P1 | P2 | P3 | reasons | context |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for rep in result["configurations"]:
            pops, cov = rep["populations"], rep["coverage"]
            reasons = "; ".join(f"{p}: {', '.join(cov[p]['reasons'])}"
                                for p in ("P1", "P2", "P3")
                                if not cov[p]["supported"])
            if not rep.get("a_informative", True):
                reasons = ("A outside the headroom band: reported, not "
                           "counted; " + reasons)
            out.append(
                f"| {rep['model']} {rep['frame']} B{rep['b_limit']} | "
                f"{_fmt(rep['p_a'])} | "
                + " | ".join(str(len(pops[g])) for g in R.GROUPS) + " | "
                + " | ".join("✓" if cov[p]["supported"] else "✗"
                             for p in ("P1", "P2", "P3"))
                + f" | {reasons or '—'} | {', '.join(rep['context']) or '—'} |")
        feas = result["feasibility"]
        out += ["", "## Feasibility target", "",
                f"Each contrast needs support in ≥ {cfg.feasibility_min_configs}"
                f" of {feas['planned_configurations']} configurations, ≥ "
                f"{cfg.feasibility_min_models} models and both B limits.", ""]
        for p in ("P1", "P2", "P3"):
            f = feas[p]
            out.append(f"- **{p}**: {'feasible' if f['feasible'] else 'NOT feasible'}"
                       f" — {f['supported_configurations']} configurations "
                       f"({f['coverage_share']:.0%}), models {len(f['models'])}, "
                       f"B {f['b_limits']}"
                       + (f"; {'; '.join(f['failures'])}" if f["failures"] else "")
                       + (f"; reasons {f['reason_counts']}" if f["reason_counts"]
                          else ""))
        out += ["", "## Raw versus chance-corrected matching", ""]
        changed = 0
        for rep in result["configurations"]:
            diff = rep["raw_vs_iota"]
            if any(diff[g]["raw_only"] or diff[g]["iota_only"] for g in diff):
                changed += 1
                out.append(f"- {rep['model']} {rep['frame']} B{rep['b_limit']}: "
                           + "; ".join(f"{g} raw-only {diff[g]['raw_only']}, "
                                       f"iota-only {diff[g]['iota_only']}"
                                       for g in ("G1", "G3", "G5")
                                       if diff[g]["raw_only"] or
                                       diff[g]["iota_only"]))
        if not changed:
            out.append("- Raw and iota matching select the same references in "
                       "every configuration.")
        out += ["", "Coverage here is a count of eligible, compatible, matched "
                "references. It says nothing about the precision of any later "
                "interference estimate: a supported contrast can still be "
                "imprecise, and an unsupported one is unavailable, not null."]
    return "\n".join(out) + "\n"
