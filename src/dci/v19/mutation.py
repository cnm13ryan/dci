"""The section 8.7 boundary-mutation battery, aimed at decision boundaries.

    "Each constraint template also receives at least 1,000 automated boundary
    mutations covering applicable off-by-one, duplication, omission,
    forbidden-item, ordering, formatting, Unicode, and parser-edge cases.
    Property-based testing is evidence about implementation invariants rather than
    a proof of natural-language semantics."

The count is easy to satisfy dishonestly - a thousand random whitespace edits would
reach it and test nothing - so every mutation here is generated by applying a named
transform at a named position, and each transform is declared with the constraints
it is EXPECTED to affect. A mutation whose observed effect differs from its
declaration is recorded as collateral, and collateral is the measurement this
battery exists to produce.

WHY COLLATERAL IS THE POINT
---------------------------
Section 4.2 says Pair 1's count and ordering verdicts may move together "through
shared parsing rather than through genuine interference", and section 4.4 says the
same of Pair 3's segmentation. A mutation that removes a list marker is declared to
affect every clause reading the list span, because it genuinely does; a mutation
that swaps two items is declared to affect only the ordering clause. When the
observed vector disagrees with either declaration, the battery has found a coupling
the audit needs to know about rather than a test to adjust.
"""
from __future__ import annotations

import enum
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any

from dci.provenance.hashes import sha
from dci.v19 import pairs
from dci.v19.certification import run_conjunction
from dci.v19.encoding import ClauseKind, Composition
from dci.v19.parsing import ListPolicy
from dci.v19.witness import construct_witness

# Section 8.7's floor, per constraint template.
MUTATIONS_PER_TEMPLATE = 1_000

ZERO_WIDTH = "\u200b"
CYRILLIC_A = "а"


class Boundary(str, enum.Enum):
    """Which scientific decision boundary a transform aims at."""

    OFF_BY_ONE = "off_by_one"
    DUPLICATION = "duplication"
    OMISSION = "omission"
    FORBIDDEN_ITEM = "forbidden_item"
    ORDERING = "ordering"
    FORMATTING = "formatting"
    UNICODE = "unicode"
    PARSER_EDGE = "parser_edge"


# The clause families each transform is declared to affect. `PARSER_SPAN` means
# every clause that reads the list segmentation, which is the coupling itself.
PARSER_SPAN = (ClauseKind.EXACT_ITEM_COUNT, ClauseKind.ITEM_PRECEDENCE)
SENTENCE_SPAN = (ClauseKind.EXACT_SENTENCE_COUNT,
                 ClauseKind.INCREASING_SENTENCE_LENGTHS)


@dataclass(frozen=True)
class Transform:
    """One named, positioned mutation with its declared expected effect."""
    name: str
    boundary: Boundary
    field_changed: str
    expected_kinds: tuple[ClauseKind, ...]
    rationale: str


TRANSFORMS: tuple[Transform, ...] = (
    Transform("segment_removed", Boundary.OFF_BY_ONE, "n_items/n_sentences",
              PARSER_SPAN + SENTENCE_SPAN + (ClauseKind.MANDATORY_TOKENS,),
              "N -> N-1 on whichever span the composition counts. It also deletes "
              "whatever words that segment carried, so a mandatory token can go "
              "with it"),
    Transform("segment_appended", Boundary.OFF_BY_ONE, "n_items/n_sentences",
              PARSER_SPAN + SENTENCE_SPAN,
              "N -> N+1, and an undeclared item under a strict policy"),
    Transform("segments_swapped", Boundary.ORDERING, "item_position",
              (ClauseKind.ITEM_PRECEDENCE,
               ClauseKind.INCREASING_SENTENCE_LENGTHS),
              "one adjacent transposition: the minimal ordering violation. It also "
              "reorders the length sequence, so the monotone clause moves with it"),
    Transform("segments_reversed", Boundary.ORDERING, "item_position",
              (ClauseKind.ITEM_PRECEDENCE,
               ClauseKind.INCREASING_SENTENCE_LENGTHS),
              "every declared precedence reversed at once, and the length sequence "
              "with it"),
    Transform("word_duplicated", Boundary.DUPLICATION, "token_multiplicity",
              (ClauseKind.ALL_TOKENS_DISTINCT,
               ClauseKind.INCREASING_SENTENCE_LENGTHS),
              "a repeated token, which also lengthens one segment"),
    Transform("word_removed", Boundary.OMISSION, "token_multiplicity",
              (ClauseKind.MANDATORY_TOKENS,
               ClauseKind.INCREASING_SENTENCE_LENGTHS),
              "a missing token, which also shortens one segment"),
    Transform("lengths_equalised", Boundary.OFF_BY_ONE, "sentence_length",
              (ClauseKind.INCREASING_SENTENCE_LENGTHS,),
              "adjacent lengths made equal: exactly at the strict-increase boundary"),
    Transform("segment_merged", Boundary.PARSER_EDGE, "n_sentences",
              PARSER_SPAN + SENTENCE_SPAN,
              "two adjacent segments joined into one, which is a parser-edge "
              "change rather than a count change the model chose"),
    Transform("segment_split", Boundary.PARSER_EDGE, "n_sentences",
              PARSER_SPAN + SENTENCE_SPAN,
              "one segment split into two, the inverse parser-edge case"),
    Transform("marker_removed", Boundary.PARSER_EDGE, "list_segmentation",
              PARSER_SPAN,
              "the shared-parser confound of section 4.2, isolated"),
    Transform("marker_space_removed", Boundary.PARSER_EDGE, "list_segmentation",
              PARSER_SPAN,
              "'- x' -> '-x', which the candidate policy does not admit"),
    Transform("marker_numbered", Boundary.FORMATTING, "list_segmentation",
              PARSER_SPAN,
              "a bullet marker replaced by an enumerated one"),
    Transform("segment_indented", Boundary.FORMATTING, "list_segmentation",
              PARSER_SPAN,
              "an item indented, which nesting policy decides"),
    Transform("empty_item_appended", Boundary.FORBIDDEN_ITEM, "list_segmentation",
              PARSER_SPAN,
              "a marker with no content, which the empty-item policy decides"),
    Transform("zero_width_inserted", Boundary.UNICODE, "token_multiplicity",
              (ClauseKind.ITEM_PRECEDENCE, ClauseKind.MANDATORY_TOKENS,
               ClauseKind.INCREASING_SENTENCE_LENGTHS),
              "a zero-width space inside a word. It is invisible to the frozen "
              "word tokenisation - the audit's demonstrated defect - so the "
              "distinctness clause is declared unaffected; but item "
              "identification matches the label against the raw item text, and a "
              "split word is no longer the mandatory token, so the precedence and "
              "mandatory-token clauses ARE affected. The battery found that "
              "asymmetry: the same character defeats presence and identification "
              "while leaving uniqueness satisfied"),
    Transform("homoglyph_substituted", Boundary.UNICODE, "token_multiplicity",
              (ClauseKind.ITEM_PRECEDENCE, ClauseKind.MANDATORY_TOKENS,
               ClauseKind.INCREASING_SENTENCE_LENGTHS),
              "a Cyrillic look-alike, with the same asymmetries: invisible to "
              "distinctness, visible to presence, to label matching, and to the "
              "length unit, because a split word counts as two words"),
    Transform("case_flipped", Boundary.UNICODE, "token_multiplicity",
              (),
              "declared to affect nothing: the frozen tokenisation case-folds and "
              "so, under the candidate policy, does label matching"),
)

TRANSFORM_BY_NAME: Mapping[str, Transform] = {t.name: t for t in TRANSFORMS}


class MutationError(RuntimeError):
    """A battery could not be produced as declared."""


@dataclass(frozen=True)
class MutationRecord:
    """One mutation, its declaration, and what actually happened."""
    template_id: str
    composition_id: str
    base_witness_hash: str
    mutation_id: str
    mutation_type: str
    boundary: str
    seed: int
    position: int
    field_changed: str
    expected_affected: tuple[str, ...]
    observed_affected: tuple[str, ...]
    observed_vector: tuple[int | None, ...]
    mutated_hash: str

    @property
    def collateral(self) -> tuple[str, ...]:
        """Constraints that moved without being declared to."""
        return tuple(c for c in self.observed_affected
                     if c not in self.expected_affected)

    @property
    def unrealised(self) -> tuple[str, ...]:
        """Constraints declared to move that did not."""
        return tuple(c for c in self.expected_affected
                     if c not in self.observed_affected)

    def describe(self) -> dict[str, Any]:
        return {"template_id": self.template_id,
                "composition_id": self.composition_id,
                "base_witness_hash": self.base_witness_hash,
                "mutation_id": self.mutation_id,
                "mutation_type": self.mutation_type, "boundary": self.boundary,
                "seed": self.seed, "position": self.position,
                "field_changed": self.field_changed,
                "expected_affected": list(self.expected_affected),
                "observed_affected": list(self.observed_affected),
                "observed_vector": list(self.observed_vector),
                "collateral": list(self.collateral),
                "unrealised": list(self.unrealised),
                "mutated_hash": self.mutated_hash}


# ------------------------------------------------------------ the transforms

def _segments(text: str) -> tuple[list[list[str]], bool]:
    """Round-trip a constructed witness into segments of word tokens."""
    if "\n" in text or text.lstrip().startswith("- "):
        rows = [line for line in text.split("\n") if line.strip()]
        return [row.lstrip().removeprefix("- ").split() for row in rows], True
    rows = [part for part in text.split(". ") if part.strip()]
    return [part.rstrip(".").split() for part in rows], False


def _render(segments: Sequence[Sequence[str]], as_list: bool) -> str:
    if as_list:
        return "\n".join("- " + " ".join(words) if words else "- "
                         for words in segments)
    return " ".join(" ".join(words) + "." for words in segments if words)


def apply_transform(name: str, text: str, position: int) -> str | None:
    """Mutate one witness. `None` means the transform does not apply here."""
    if name not in TRANSFORM_BY_NAME:
        raise MutationError(f"{name!r} is not a declared transform")
    segments, as_list = _segments(text)
    if not segments:
        return None
    words = [list(segment) for segment in segments]

    if name == "segment_removed":
        if len(words) < 2 or position >= len(words):
            return None
        del words[position]
    elif name == "segment_appended":
        words.insert(min(position, len(words)), ["extraitem"])
    elif name == "segments_swapped":
        if position + 1 >= len(words):
            return None
        words[position], words[position + 1] = words[position + 1], words[position]
    elif name == "segments_reversed":
        if len(words) < 2:
            return None
        words.reverse()
    elif name == "word_duplicated":
        if position >= len(words) or not words[position]:
            return None
        words[position] = words[position] + [words[position][0]]
    elif name == "word_removed":
        if position >= len(words) or len(words[position]) < 1:
            return None
        words[position] = words[position][1:]
        if not words[position]:
            return None
    elif name == "lengths_equalised":
        if position + 1 >= len(words) or not words[position]:
            return None
        target = len(words[position])
        source = words[position + 1]
        if len(source) == target:
            return None
        words[position + 1] = (source[:target] if len(source) > target
                               else source + [f"pad{i}" for i in
                                              range(target - len(source))])
    elif name == "segment_merged":
        if position + 1 >= len(words):
            return None
        words[position] = words[position] + words[position + 1]
        del words[position + 1]
    elif name == "segment_split":
        if position >= len(words) or len(words[position]) < 2:
            return None
        half = len(words[position]) // 2
        tail = words[position][half:]
        words[position] = words[position][:half]
        words.insert(position + 1, tail)
    elif name in ("marker_removed", "marker_space_removed", "marker_numbered",
                  "segment_indented", "empty_item_appended"):
        if not as_list:
            return None
        rendered = _render(words, True).split("\n")
        if name == "empty_item_appended":
            rendered.append("- ")
        else:
            if position >= len(rendered):
                return None
            line = rendered[position]
            if name == "marker_removed":
                rendered[position] = line.removeprefix("- ")
            elif name == "marker_space_removed":
                rendered[position] = line.replace("- ", "-", 1)
            elif name == "marker_numbered":
                rendered[position] = line.replace("- ", f"{position + 1}. ", 1)
            else:
                rendered[position] = "  " + line
        return "\n".join(rendered)
    elif name in ("zero_width_inserted", "homoglyph_substituted", "case_flipped"):
        flat = [(i, j) for i, segment in enumerate(words)
                for j in range(len(segment))]
        if not flat:
            return None
        row, column = flat[position % len(flat)]
        word = words[row][column]
        if name == "zero_width_inserted":
            if len(word) < 2:
                return None
            words[row][column] = word[:1] + ZERO_WIDTH + word[1:]
        elif name == "homoglyph_substituted":
            if "a" not in word:
                return None
            words[row][column] = word.replace("a", CYRILLIC_A, 1)
        else:
            if word == word.upper():
                return None
            words[row][column] = word.upper()
    else:                                              # pragma: no cover - guarded
        raise MutationError(f"{name!r} has no implementation")
    return _render(words, as_list)


# ---------------------------------------------------------------- the battery

def _expected(composition: Composition, transform: Transform,
              policy: ListPolicy) -> tuple[str, ...]:
    """Which constraints this transform should move, GIVEN the frozen policy.

    Several expectations are policy-conditional, and that is the clearest
    demonstration of why the policy must be frozen before Stage 2 can certify
    anything: the same edit is a scientific perturbation under one policy and a
    formatting no-op under another.
    """
    kinds = set(transform.expected_kinds)
    if transform.name == "marker_numbered" and policy.numbered_items_count:
        kinds -= set(PARSER_SPAN)          # an enumerated item is still an item
    if transform.name == "segment_indented" and policy.nested_items_count:
        kinds -= set(PARSER_SPAN)          # an indented item is still an item
    if transform.name == "empty_item_appended" and not policy.empty_items_count:
        kinds -= set(PARSER_SPAN)          # a contentless marker is not an item
    if transform.name == "segment_appended" and policy.extra_items_permitted:
        kinds.discard(ClauseKind.ITEM_PRECEDENCE)   # an undeclared item is legal
    if transform.name in ("zero_width_inserted", "homoglyph_substituted") \
            and policy.label_match == "leading_label":
        kinds.discard(ClauseKind.ITEM_PRECEDENCE)   # only a leading edit would tell
    if transform.name == "case_flipped" and policy.label_case_sensitive:
        kinds.add(ClauseKind.ITEM_PRECEDENCE)
    return tuple(clause.constraint_id for clause in composition.clauses
                 if clause.kind in kinds)


def run_battery(composition: Composition, policy: ListPolicy, *,
                template_id: str, seed: int = 0,
                target: int = MUTATIONS_PER_TEMPLATE) -> tuple[MutationRecord, ...]:
    """Every distinct mutation this base admits, up to `target`.

    Deterministic in `(composition, policy, seed)`. Returns fewer than `target`
    when the base is exhausted rather than padding: the section 8.7 floor is a
    floor on coverage, so reaching it by repeating an edit would be the failure the
    floor exists to prevent. `assert_battery_is_evidence` enforces the count.
    """
    base = construct_witness(composition, seed=seed)
    if not base.constructed or base.text is None:
        raise MutationError(
            f"{composition.composition_id}: no base witness to mutate "
            f"({base.reason})")
    reference = run_conjunction(composition, base.text, policy)
    if not reference.complete or reference.v_all != 1:
        raise MutationError(
            f"{composition.composition_id}: the base witness is not accepted by "
            f"every verifier (vector {reference.vector}), so a mutation's effect "
            "could not be attributed")

    segments, _ = _segments(base.text)
    # One position per segment, plus two past the end so the boundary transforms
    # can act at the edges. Derived from the witness rather than fixed, so a larger
    # parameter realisation contributes proportionally more coverage.
    positions = range(len(segments) + 2)

    records: list[MutationRecord] = []
    seen: set[str] = {base.text}
    for transform in TRANSFORMS:
        for position in positions:
            mutated = apply_transform(transform.name, base.text, position)
            # Distinct TEXTS, not distinct (transform, position) pairs: a transform
            # that is a no-op at this position would otherwise pad the count.
            if mutated is None or mutated in seen:
                continue
            seen.add(mutated)
            observed = run_conjunction(composition, mutated, policy)
            affected = tuple(constraint for constraint in composition.constraint_ids
                             if _flipped(reference, observed, constraint))
            records.append(MutationRecord(
                template_id=template_id,
                composition_id=composition.composition_id,
                base_witness_hash=base.witness_hash,
                mutation_id=sha(["v19/mutation", template_id,
                                 composition.encoding_hash, transform.name,
                                 position, seed]),
                mutation_type=transform.name, boundary=transform.boundary.value,
                seed=seed, position=position,
                field_changed=transform.field_changed,
                expected_affected=_expected(composition, transform, policy),
                observed_affected=affected, observed_vector=observed.vector,
                mutated_hash=sha(["v19/witness", mutated])))
            if len(records) >= target:
                return tuple(records)
    return tuple(records)


def template_bases(pair_id: str, policy: ListPolicy, *,
                   settings: Sequence[int] = tuple(range(2, 31))
                   ) -> tuple[Composition, ...]:
    """A family of base compositions for one pair's A+B template.

    The section 8.7 floor is reached by varying the *parameter realisation* across
    a pair's admissible-looking range and mutating each, not by re-running one
    transform. The settings here are a test range, not a calibrated grid: the
    frozen grid is a Stage 5 output (D6) and is deliberately not anticipated.
    """
    from dci.v19.encoding import encode_composition
    from dci.v19.parsing import OrderingRelation

    out: list[Composition] = []
    for index, size in enumerate(settings):
        if pair_id == "p1":
            # Zero-padded so no label is a substring of another: under
            # containment matching "item1" would be found inside "item10" and both
            # items would be ambiguous. That is a real constraint on whatever
            # label vocabulary Stage 5 eventually calibrates, not a test detail.
            labels = tuple(f"item{i:03d}" for i in range(size))
            edges = tuple((labels[i], labels[i + 1]) for i in range(size - 1))
            relation = OrderingRelation(items=labels, edges=edges)
            realisations = {
                pairs.PAIR_1.target.constraint_id: {"n_items": size,
                                                    "policy": policy},
                pairs.PAIR_1.focal.constraint_id: {"relation": relation,
                                                   "policy": policy}}
        elif pair_id == "p2":
            realisations = {
                pairs.PAIR_2.target.constraint_id: {
                    "mandatory_words": tuple(f"token{i:03d}"
                                             for i in range(size))},
                pairs.PAIR_2.focal.constraint_id: {}}
        else:
            realisations = {
                pairs.PAIR_3.target.constraint_id: {"n_sentences": size},
                pairs.PAIR_3.focal.constraint_id: {}}
        out.append(encode_composition(
            f"{pair_id}/mutation-base-{index}", pair_id=pair_id, arm="B", load=2,
            realisations=realisations))
    return tuple(out)


def battery_for_template(template_id: str, compositions: Sequence[Composition],
                         policy: ListPolicy, *, seed: int = 0,
                         target: int = MUTATIONS_PER_TEMPLATE
                         ) -> tuple[MutationRecord, ...]:
    """Run the battery across a family of base compositions until `target`.

    Coverage first: each base contributes every distinct mutation it admits before
    the next is used, so the floor is reached by covering more parameter
    realisations and more positions rather than by repeating one transform.
    """
    if not compositions:
        raise MutationError("a battery needs at least one base composition")
    records: list[MutationRecord] = []
    for composition in compositions:
        records.extend(run_battery(composition, policy, template_id=template_id,
                                   seed=seed, target=target - len(records)))
        if len(records) >= target:
            break
    return tuple(records)


def _flipped(reference, observed, constraint: str) -> bool:
    before = reference.outcomes.get(constraint)
    after = observed.outcomes.get(constraint)
    if before is None or after is None:
        return True
    if before.scored != after.scored:
        return True
    return before.verdict is not after.verdict


def summarise(records: Sequence[MutationRecord]) -> dict[str, Any]:
    """The battery's evidence, per template."""
    if not records:
        return {"n_mutations": 0, "templates": [], "by_type": {},
                "by_boundary": {}, "distinct_mutations": 0, "distinct_texts": 0,
                "n_collateral": 0, "collateral": [], "n_unrealised": 0,
                "unrealised": [], "meets_floor": False}
    by_type: dict[str, int] = {}
    by_boundary: dict[str, int] = {}
    collateral: list[dict[str, Any]] = []
    unrealised: list[dict[str, Any]] = []
    for record in records:
        by_type[record.mutation_type] = by_type.get(record.mutation_type, 0) + 1
        by_boundary[record.boundary] = by_boundary.get(record.boundary, 0) + 1
        if record.collateral:
            collateral.append({"mutation_type": record.mutation_type,
                               "position": record.position,
                               "collateral": list(record.collateral)})
        if record.unrealised:
            unrealised.append({"mutation_type": record.mutation_type,
                               "position": record.position,
                               "unrealised": list(record.unrealised)})
    return {"n_mutations": len(records),
            "templates": sorted({r.template_id for r in records}),
            "by_type": dict(sorted(by_type.items())),
            "by_boundary": dict(sorted(by_boundary.items())),
            "distinct_mutations": len({r.mutation_id for r in records}),
            "distinct_texts": len({r.mutated_hash for r in records}),
            "n_collateral": len(collateral), "collateral": collateral[:32],
            "n_unrealised": len(unrealised), "unrealised": unrealised[:32],
            "meets_floor": len(records) >= MUTATIONS_PER_TEMPLATE}


def assert_battery_is_evidence(records: Sequence[MutationRecord]) -> dict[str, Any]:
    """A battery that met the count by repetition is not evidence.

    Section 8.7's floor is a floor on *coverage*, so the checks are that the count
    is met, that the mutated texts are genuinely distinct, and that the boundaries
    named in section 8.7 are actually represented rather than one transform run a
    thousand times.
    """
    summary = summarise(records)
    problems = []
    if not summary["meets_floor"]:
        problems.append(f"{summary['n_mutations']} mutations, below the floor of "
                        f"{MUTATIONS_PER_TEMPLATE}")
    if summary.get("distinct_texts", 0) != summary["n_mutations"]:
        problems.append(
            f"{summary['n_mutations']} mutations produced only "
            f"{summary['distinct_texts']} distinct texts, so the count is padded")
    represented = set(summary.get("by_boundary", {}))
    if len(represented) < 4:
        problems.append(
            f"only {sorted(represented)} boundaries are represented; section 8.7 "
            "names off-by-one, duplication, omission, forbidden-item, ordering, "
            "formatting, Unicode and parser-edge cases")
    if problems:
        raise MutationError("the mutation battery is not evidence:\n  - "
                            + "\n  - ".join(problems))
    return summary
