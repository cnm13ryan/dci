"""The inference-backend contract.

v15 records `engine` inside the execution condition, and every committed batch
carries the execution fingerprint plus the tokenizer state, so a response
generated by one backend can never be silently consumed by a run frozen on
another. A backend implementation must therefore preserve, exactly:

  * rendered prompts and the chat-template identity used to render them;
  * tokenizer identity (vocabulary/special-token/chat-template hashes);
  * fixed decoding parameters and per-batch seeds;
  * batch membership as given by the frozen batch plan — never re-batched;
  * generated text, per-row token counts, EOS state, truncation flags and
    stop reason (the TERMINATION_RECORDS contract);
  * the execution fingerprint fields it contributes (engine, dtype,
    attention implementation).

Backends read the shared run state module (`dci.pipeline.state`) exactly as
the notebook cell they were extracted from did; the state module documents
that discipline. vLLM or any other engine may be added ONLY as a new value of
`CFG.engine` (a new execution condition), with parity tests, and never as a
drop-in substitution inside an existing frozen run.
"""
from __future__ import annotations

from typing import Any, Protocol


class InferenceBackend(Protocol):
    name: str

    def load_model(self):                                    # -> (tokenizer, model)
        ...

    def free_model(self) -> None:
        ...

    @property
    def tokenizer(self):
        ...

    def generate(self, batch_rows: list[dict[str, Any]],
                 batch_seed: int) -> tuple[list[str], dict[str, Any]]:
        ...
